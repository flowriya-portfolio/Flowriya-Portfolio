/* ================= LOCAL STORAGE ================= */

let cartData = JSON.parse(localStorage.getItem("luxoraCart")) || [];

let wishlistData = JSON.parse(localStorage.getItem("luxoraWishlist")) || [];

/* ================= FIX OLD WISHLIST DATA ================= */

/*
   Agar purani wishlist mein objects save hain,
   unko sirf IDs mein convert kar raha hai.
*/

wishlistData = wishlistData
  .map(function (item) {
    if (typeof item === "object") {
      return Number(item.id);
    }

    return Number(item);
  })
  .filter(function (id) {
    return !isNaN(id);
  });

localStorage.setItem("luxoraWishlist", JSON.stringify(wishlistData));

/* ================= SAVE ================= */

function saveCart() {
  localStorage.setItem("luxoraCart", JSON.stringify(cartData));
}

function saveWishlist() {
  localStorage.setItem("luxoraWishlist", JSON.stringify(wishlistData));
}

/* ================= DISPLAY PRODUCTS ================= */

function displayProducts(list) {
  if (!productsGrid) {
    return;
  }

  productsGrid.innerHTML = "";

  if (list.length === 0) {
    productsGrid.innerHTML = `

      <div class="empty-cart">

        <i class="fa-solid fa-magnifying-glass"></i>

        <h3>No products found</h3>

        <p>
          Try searching for another product.
        </p>

      </div>

    `;

    return;
  }

  list.forEach(function (product) {
    const liked = wishlistData.includes(product.id);

    const card = document.createElement("article");

    card.className = "product";

    card.innerHTML = `

      <div class="product-image">

        <span class="product-tag">
          ${product.tag}
        </span>


        <button
          class="wishlist ${liked ? "liked" : ""}"
          data-id="${product.id}"
          type="button"
        >

          <i class="${liked ? "fa-solid" : "fa-regular"} fa-heart"></i>

        </button>


        <img
          src="${product.image}"
          alt="${product.name}"
        >

      </div>


      <div class="product-info">

        <span class="product-category">
          ${product.category}
        </span>


        <h3>
          ${product.name}
        </h3>


        <p>
          ${product.description}
        </p>


        <div class="product-bottom">

          <strong class="product-price">
            $${product.price}
          </strong>


          <button
            class="add-cart"
            data-id="${product.id}"
            type="button"
          >
            Add to Bag
          </button>

        </div>

      </div>

    `;

    /* PRODUCT DETAILS */

    card.addEventListener("click", function (event) {
      if (
        event.target.closest(".add-cart") ||
        event.target.closest(".wishlist")
      ) {
        return;
      }

      localStorage.setItem("luxoraSelectedProduct", JSON.stringify(product));

      window.location.href = "product.html";
    });

    productsGrid.appendChild(card);
  });

  productEvents();
}

/* ================= PRODUCT EVENTS ================= */

function productEvents() {
  document.querySelectorAll(".add-cart").forEach(function (button) {
    button.addEventListener("click", function () {
      const id = Number(button.dataset.id);

      addToCart(id);
    });
  });

  document.querySelectorAll(".wishlist").forEach(function (button) {
    button.addEventListener("click", function () {
      const id = Number(button.dataset.id);

      toggleWishlist(id);
    });
  });
}

/* ================= CART ================= */

function addToCart(id) {
  const product = products.find(function (item) {
    return item.id === id;
  });

  if (!product) {
    return;
  }

  const existing = cartData.find(function (item) {
    return item.id === id;
  });

  if (existing) {
    existing.quantity++;

    showToast("Quantity updated");
  } else {
    cartData.push({
      id: product.id,

      name: product.name,

      price: product.price,

      image: product.image,

      quantity: 1,
    });

    showToast("Added to your bag");
  }

  saveCart();

  updateCart();
}

/* ================= UPDATE CART ================= */

function updateCart() {
  let total = 0;

  let count = 0;

  cartData.forEach(function (item) {
    total += item.price * item.quantity;

    count += item.quantity;
  });

  if (cartCount) {
    cartCount.textContent = count;
  }

  if (sideCartCount) {
    sideCartCount.textContent = count;
  }

  if (cartTotal) {
    cartTotal.textContent = "$" + total;
  }

  if (!cartContent) {
    return;
  }

  cartContent.innerHTML = "";

  if (cartData.length === 0) {
    cartContent.innerHTML = `

      <div class="empty-cart">

        <i class="fa-solid fa-bag-shopping"></i>

        <h3>Your Bag is Empty</h3>

        <p>
          Discover something beautiful
          and add it to your collection.
        </p>

        <button
          id="startShopping"
          type="button"
        >
          Start Shopping
        </button>

      </div>

    `;

    const startShopping = document.querySelector("#startShopping");

    if (startShopping) {
      startShopping.addEventListener("click", function () {
        closeCartPanel();

        window.location.href = "menu.html";
      });
    }

    return;
  }

  cartData.forEach(function (item) {
    const cartItem = document.createElement("div");

    cartItem.className = "cart-item";

    cartItem.innerHTML = `

      <img
        src="${item.image}"
        alt="${item.name}"
      >


      <div class="cart-item-info">

        <h4>
          ${item.name}
        </h4>


        <p>
          $${item.price}
        </p>


        <div class="quantity">

          <button
            class="minus"
            data-id="${item.id}"
            type="button"
          >
            −
          </button>


          <span>
            ${item.quantity}
          </span>


          <button
            class="plus"
            data-id="${item.id}"
            type="button"
          >
            +
          </button>

        </div>

      </div>


      <button
        class="remove-item"
        data-id="${item.id}"
        type="button"
      >

        <i class="fa-solid fa-trash"></i>

      </button>

    `;

    cartContent.appendChild(cartItem);
  });

  cartItemEvents();
}

/* ================= CART EVENTS ================= */

function cartItemEvents() {
  document.querySelectorAll(".minus").forEach(function (button) {
    button.addEventListener("click", function () {
      const id = Number(button.dataset.id);

      const item = cartData.find(function (item) {
        return item.id === id;
      });

      if (!item) {
        return;
      }

      if (item.quantity > 1) {
        item.quantity--;
      } else {
        cartData = cartData.filter(function (item) {
          return item.id !== id;
        });
      }

      saveCart();

      updateCart();
    });
  });

  document.querySelectorAll(".plus").forEach(function (button) {
    button.addEventListener("click", function () {
      const id = Number(button.dataset.id);

      const item = cartData.find(function (item) {
        return item.id === id;
      });

      if (item) {
        item.quantity++;

        saveCart();

        updateCart();
      }
    });
  });

  document.querySelectorAll(".remove-item").forEach(function (button) {
    button.addEventListener("click", function () {
      const id = Number(button.dataset.id);

      cartData = cartData.filter(function (item) {
        return item.id !== id;
      });

      saveCart();

      updateCart();

      showToast("Removed from your bag");
    });
  });
}

/* ================= WISHLIST ================= */

function toggleWishlist(id) {
  if (wishlistData.includes(id)) {
    wishlistData = wishlistData.filter(function (item) {
      return item !== id;
    });

    showToast("Removed from wishlist");
  } else {
    wishlistData.push(id);

    showToast("Added to wishlist");
  }

  saveWishlist();

  updateWishlist();

  displayProducts(getProducts());
}

/* ================= UPDATE WISHLIST ================= */

function updateWishlist() {
  if (wishlistCount) {
    wishlistCount.textContent = wishlistData.length;
  }

  if (sideWishlistCount) {
    sideWishlistCount.textContent = wishlistData.length;
  }
}

