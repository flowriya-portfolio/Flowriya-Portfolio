/* ================= FILTER ================= */

let currentCategory = "All";

filters.forEach(function (filter) {
  filter.addEventListener("click", function () {
    filters.forEach(function (item) {
      item.classList.remove("active");
    });

    filter.classList.add("active");

    currentCategory = filter.dataset.category;

    displayProducts(getProducts());
  });
});

function getProducts() {
  let list = products;

  if (currentCategory !== "All") {
    list = products.filter(function (product) {
      return product.category === currentCategory;
    });
  }

  if (searchInput) {
    const search = searchInput.value.trim().toLowerCase();

    if (search !== "") {
      list = list.filter(function (product) {
        return (
          product.name.toLowerCase().includes(search) ||
          product.category.toLowerCase().includes(search) ||
          product.description.toLowerCase().includes(search)
        );
      });
    }
  }

  return list;
}

/* ================= SEARCH ================= */

if (searchBtn && searchBox && searchInput) {
  searchBtn.addEventListener("click", function () {
    searchBox.classList.add("active");

    searchInput.focus();
  });
}

if (searchInput) {
  searchInput.addEventListener("input", function () {
    displayProducts(getProducts());
  });
}

if (clearSearch && searchBox && searchInput) {
  clearSearch.addEventListener("click", function () {
    searchInput.value = "";

    searchBox.classList.remove("active");

    displayProducts(getProducts());

    searchInput.blur();
  });
}

/* ================= SIDEBAR ================= */

function openSidebar() {
  if (!sidebar) {
    return;
  }

  sidebar.classList.add("open");

  if (overlay) {
    overlay.classList.add("active");
  }

  document.body.classList.add("no-scroll");
}

function closeSidebarPanel() {
  if (!sidebar) {
    return;
  }

  sidebar.classList.remove("open");

  if (overlay) {
    overlay.classList.remove("active");
  }

  document.body.classList.remove("no-scroll");
}

if (menuBtn) {
  menuBtn.addEventListener("click", openSidebar);
}

if (closeSidebar) {
  closeSidebar.addEventListener("click", closeSidebarPanel);
}

if (overlay) {
  overlay.addEventListener("click", closeSidebarPanel);
}

/* ================= CART PANEL ================= */

function openCart() {
  if (!cart) {
    return;
  }

  cart.classList.add("active");

  if (cartOverlay) {
    cartOverlay.classList.add("active");
  }

  document.body.classList.add("no-scroll");

  updateCart();
}

function closeCartPanel() {
  if (!cart) {
    return;
  }

  cart.classList.remove("active");

  if (cartOverlay) {
    cartOverlay.classList.remove("active");
  }

  document.body.classList.remove("no-scroll");
}

if (cartBtn) {
  cartBtn.addEventListener("click", openCart);
}

if (sideCartBtn) {
  sideCartBtn.addEventListener("click", function (event) {
    event.preventDefault();

    closeSidebarPanel();

    openCart();
  });
}

if (closeCart) {
  closeCart.addEventListener("click", closeCartPanel);
}

if (cartOverlay) {
  cartOverlay.addEventListener("click", closeCartPanel);
}

/* ================= TOAST ================= */

let toastTimer;

function showToast(message) {
  if (!toast || !toastMessage) {
    return;
  }

  toastMessage.textContent = message;

  toast.classList.add("show");

  clearTimeout(toastTimer);

  toastTimer = setTimeout(function () {
    toast.classList.remove("show");
  }, 2200);
}

/* ================= NEWSLETTER ================= */

if (newsletterForm) {
  newsletterForm.addEventListener("submit", function (event) {
    event.preventDefault();

    showToast("Welcome to the LUXORA inner circle");

    newsletterForm.reset();
  });
}

/* ================= CHECKOUT ================= */

if (checkoutBtn) {
  checkoutBtn.addEventListener("click", function () {
    if (cartData.length === 0) {
      showToast("Your bag is empty");

      return;
    }

    window.location.href = "order.html";
  });
}

